"""Rebuild assets/js/eye-data.js from the two ASCII scene exports in source/.

    python tools/build_eye_data.py

Inputs  : source/ascii-eye-open.html    (eye open, HUD reflected in the iris)
          source/ascii-eye-closed.html  (same framing, eyelid closed -> used for the blink)
Output  : assets/js/eye-data.js  ->  window.EYE = { w, h, open:{c,k}, closed:{c,k}, mask, iris }
            c    = the characters, row by row (w*h letters)
            k    = colour of every cell, 3 bytes (r,g,b) per cell, base64
            mask = 1 byte per cell, 255 where the cell is eyeball (sclera / iris / pupil), base64
            iris = centre and radius of the iris, in grid cells (radius in row units)

Both exports must use the same grid (213 x 72). Pure standard library + Pillow (for mask smoothing).
"""
import base64, json, os, re, sys
from PIL import Image, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
W, H = 213, 72
CELL_X, X0, Y0 = 0.6, -63.9, 36          # export spacing: x step 0.6, top-left cell at (-63.9, 36)


def load(name):
    src = open(os.path.join(ROOT, "source", name), encoding="utf8", errors="replace").read()
    a = src.index("const asciiData = ") + len("const asciiData = ")
    end = re.search(r"\n\};\n", src[a:]).start() + 2
    obj = re.sub(r"\b(dimensions|width|height|depthScale|backgroundColor|groups)\s*:", r'"\1":', src[a:a + end])
    data = json.loads(obj)
    assert data["dimensions"] == {"width": W, "height": H}, "unexpected grid size in " + name
    chars = [" "] * (W * H)
    rgb = bytearray(W * H * 3)
    for group in data["groups"]:
        for inst in group["instances"]:
            col = round((inst["x"] - X0) / CELL_X)
            row = round(Y0 - inst["y"])
            k = row * W + col
            h = inst["color"].lstrip("#")
            chars[k] = group["char"]
            rgb[k * 3:k * 3 + 3] = bytes((int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)))
    assert " " not in chars, "grid has holes in " + name
    return "".join(chars), rgb


def eyeball_mask(rgb):
    """Cells of the open frame that are eyeball rather than skin: cool, near-white or very dark, near the centre."""
    m = Image.new("L", (W, H), 0)
    px = m.load()
    for r in range(H):
        for c in range(W):
            R, G, B = rgb[(r * W + c) * 3:(r * W + c) * 3 + 3]
            lum = 0.299 * R + 0.587 * G + 0.114 * B
            ex, ey = (c - 100) / 62, (r - 38) / 19
            if ex * ex + ey * ey > 1:
                continue
            skin = R > G * 1.12 and R > B * 1.25
            white = lum > 150 and abs(R - B) < 60
            cool = B > R * 1.05 or G > R * 1.1
            if (white or cool or lum < 28) and not (skin and not white):
                px[c, r] = 255
    m = m.filter(ImageFilter.MedianFilter(5))
    m = m.filter(ImageFilter.MaxFilter(5)).filter(ImageFilter.MinFilter(5))   # close small holes
    return m


def main():
    oc, ok = load("ascii-eye-open.html")
    cc, ck = load("ascii-eye-closed.html")
    mask = eyeball_mask(ok)
    b64 = lambda b: base64.b64encode(bytes(b)).decode()
    eye = {
        "w": W, "h": H,
        "open": {"c": oc, "k": b64(ok)},
        "closed": {"c": cc, "k": b64(ck)},
        "mask": b64(mask.tobytes()),
        # measured on the open frame; change here if you swap the source images
        "iris": {"cx": 99, "cy": 36, "r": 27},
    }
    out = "/* Generated by tools/build_eye_data.py. Do not edit by hand. */\nwindow.EYE=" + json.dumps(eye, separators=(",", ":")) + ";\n"
    path = os.path.join(ROOT, "assets", "js", "eye-data.js")
    open(path, "w", encoding="utf8").write(out)
    cells = sum(1 for v in mask.tobytes() if v)
    print("wrote", path, len(out), "bytes;", cells, "eyeball cells")


if __name__ == "__main__":
    main()
